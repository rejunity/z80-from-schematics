#!/usr/bin/env python3
# ===========================================================================
# amalgamate.py - cfast as one header: the reference model (cmodel/), the
# generated phase steps (outdir from gen_fast.py) and both frames.
#
#   amalgamate.py gendir out.h
#
# Use (stb style):
#   #include "z80_cfast.h"            declarations: z80.h + z80_fast.h
#   #define Z80_IMPL                  in exactly one unit, before including
#   #include "z80_cfast.h"            again: the model, z80f_tick()
# and, for z80f_run(), define ZF_BUS(pins) / ZF_BOUNDARY(c) (see
# cfast/z80_fast_run.h) before an include with Z80_IMPL defined (the same
# one or a later one).
# ===========================================================================
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODEL = ["z80_alu.c", "z80_core.c", "z80_pla.c", "z80_regfile.c", "z80_timing.c"]


def expand(path, gendir, seen_sys):
    """The file with its local includes resolved: cmodel sources and z80.h /
    z80_fast.h are emitted elsewhere (dropped here), generated headers are
    inlined; system includes kept once."""
    out = []
    for line in open(path):
        m = re.match(r'\s*#\s*include\s+([<"])([^>"]+)[>"]', line)
        if not m:
            out.append(line)
            continue
        kind, name = m.groups()
        base = os.path.basename(name)
        if kind == "<":
            if name not in seen_sys:
                seen_sys.add(name)
                out.append(line)
        elif base.startswith("z80_fast_") and base.endswith(".h") and base != "z80_fast_run.h":
            out.append(f"/* ---- {base} (generated) ---- */\n")
            out += open(os.path.join(gendir, base)).readlines()
        # z80.h, z80_fast.h, ../cmodel/*.c: already in the amalgamation
    return out


def main():
    gendir, dst = sys.argv[1], sys.argv[2]
    seen = set()
    o = ["/* ============================================================================\n",
         " * z80_cfast.h - the half-cycle Z80 model with cfast's generated phase\n",
         " * engine, as one header. Generated by cfast/amalgamate.py from cmodel/,\n",
         " * cfast/ and the timing tables -- do not edit.\n",
         " *\n",
         " *   #include \"z80_cfast.h\"     declarations\n",
         " *   #define Z80_IMPL           in one unit: the implementation, z80f_tick()\n",
         " *   #include \"z80_cfast.h\"\n",
         " * Defining ZF_BUS(pins) and ZF_BOUNDARY(c) before an include with\n",
         " * Z80_IMPL also gives z80f_run() (see the run frame below).\n",
         " * ==========================================================================*/\n",
         "#ifndef Z80_CFAST_H\n#define Z80_CFAST_H\n"]
    o += expand(os.path.join(ROOT, "cmodel", "z80.h"), gendir, seen)
    o += expand(os.path.join(ROOT, "cfast", "z80_fast.h"), gendir, seen)
    o.append("#endif /* Z80_CFAST_H */\n\n")
    o.append("#if defined(Z80_IMPL) && !defined(Z80_CFAST_IMPL)\n#define Z80_CFAST_IMPL\n")
    for f in MODEL:
        o.append(f"/* ======== cmodel/{f} ======== */\n")
        o += expand(os.path.join(ROOT, "cmodel", f), gendir, seen)
    o.append("/* ======== cfast/z80_fast.c ======== */\n")
    o += expand(os.path.join(ROOT, "cfast", "z80_fast.c"), gendir, seen)
    o.append("#endif /* Z80_IMPL */\n\n")
    o.append("#if defined(Z80_IMPL) && defined(ZF_BUS) && !defined(Z80_CFAST_RUN)\n"
             "#define Z80_CFAST_RUN\n")
    o.append("/* ======== cfast/z80_fast_run.h ======== */\n")
    o += expand(os.path.join(ROOT, "cfast", "z80_fast_run.h"), gendir, seen)
    o.append("#endif /* ZF_BUS */\n")
    with open(dst, "w") as f:
        f.writelines(o)
    print(f"amalgamate: {dst}, {len(o)} lines")


if __name__ == "__main__":
    main()
