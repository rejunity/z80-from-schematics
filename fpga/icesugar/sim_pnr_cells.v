// sim_pnr_cells.v - models for the two routed-netlist cells yosys'
// cells_sim.v lacks (`make sim_pnr`).
//   ICESTORM_PLL: always locked, both outputs follow REFERENCECLK. Its
//     global buffers are fed from the clk pad by sim_pnr.py (their path
//     from the PLL is not a net), as in the RTL sims.
//   ICESTORM_SPRAM: SB_SPRAM256KA's model with the ports split into bits.
module ICESTORM_PLL (
    input  BYPASS, EXTFEEDBACK, LATCHINPUTVALUE, REFERENCECLK, RESETB, SCLK, SDI,
    input  DYNAMICDELAY_0, DYNAMICDELAY_1, DYNAMICDELAY_2, DYNAMICDELAY_3,
    input  DYNAMICDELAY_4, DYNAMICDELAY_5, DYNAMICDELAY_6, DYNAMICDELAY_7,
    output LOCK, PLLOUT_A, PLLOUT_A_GLOBAL, PLLOUT_B, PLLOUT_B_GLOBAL, SDO
);
    parameter PLLOUT_SELECT_PORTB = "GENCLK";
    parameter TEST_MODE = 1'b0, SHIFTREG_DIVMODE = 1'b0, ENABLE_ICEGATE_PORTA = 1'b0, ENABLE_ICEGATE_PORTB = 1'b0;
    parameter PLLTYPE = 32'd0, PLLOUT_SELECT_B = 32'd0;
    parameter PLLOUT_SELECT_A = 2'd0, FILTER_RANGE = 3'd0, FEEDBACK_PATH = 3'd0, DIVQ = 3'd0;
    parameter FDA_RELATIVE = 4'd0, FDA_FEEDBACK = 4'd0, DIVR = 4'd0, DIVF = 7'd0;
    parameter DELAY_ADJMODE_REL = 1'b0, DELAY_ADJMODE_FB = 1'b0;
    assign PLLOUT_A = REFERENCECLK, PLLOUT_A_GLOBAL = REFERENCECLK;
    assign PLLOUT_B = REFERENCECLK, PLLOUT_B_GLOBAL = REFERENCECLK;
    assign LOCK = 1'b1, SDO = 1'b0;
endmodule

module ICESTORM_SPRAM (
    input  ADDRESS_0, ADDRESS_1, ADDRESS_2, ADDRESS_3, ADDRESS_4, ADDRESS_5, ADDRESS_6,
    input  ADDRESS_7, ADDRESS_8, ADDRESS_9, ADDRESS_10, ADDRESS_11, ADDRESS_12, ADDRESS_13,
    input  DATAIN_0, DATAIN_1, DATAIN_2, DATAIN_3, DATAIN_4, DATAIN_5, DATAIN_6, DATAIN_7,
    input  DATAIN_8, DATAIN_9, DATAIN_10, DATAIN_11, DATAIN_12, DATAIN_13, DATAIN_14, DATAIN_15,
    input  MASKWREN_0, MASKWREN_1, MASKWREN_2, MASKWREN_3,
    input  WREN, CHIPSELECT, CLOCK, STANDBY, SLEEP, POWEROFF,
    output DATAOUT_0, DATAOUT_1, DATAOUT_2, DATAOUT_3, DATAOUT_4, DATAOUT_5, DATAOUT_6, DATAOUT_7,
    output DATAOUT_8, DATAOUT_9, DATAOUT_10, DATAOUT_11, DATAOUT_12, DATAOUT_13, DATAOUT_14, DATAOUT_15
);
    SB_SPRAM256KA ram (
        .ADDRESS ({ADDRESS_13, ADDRESS_12, ADDRESS_11, ADDRESS_10, ADDRESS_9, ADDRESS_8, ADDRESS_7,
                   ADDRESS_6, ADDRESS_5, ADDRESS_4, ADDRESS_3, ADDRESS_2, ADDRESS_1, ADDRESS_0}),
        .DATAIN  ({DATAIN_15, DATAIN_14, DATAIN_13, DATAIN_12, DATAIN_11, DATAIN_10, DATAIN_9, DATAIN_8,
                   DATAIN_7, DATAIN_6, DATAIN_5, DATAIN_4, DATAIN_3, DATAIN_2, DATAIN_1, DATAIN_0}),
        .MASKWREN({MASKWREN_3, MASKWREN_2, MASKWREN_1, MASKWREN_0}),
        .WREN(WREN), .CHIPSELECT(CHIPSELECT), .CLOCK(CLOCK),
        .STANDBY(STANDBY), .SLEEP(SLEEP), .POWEROFF(POWEROFF),
        .DATAOUT ({DATAOUT_15, DATAOUT_14, DATAOUT_13, DATAOUT_12, DATAOUT_11, DATAOUT_10, DATAOUT_9, DATAOUT_8,
                   DATAOUT_7, DATAOUT_6, DATAOUT_5, DATAOUT_4, DATAOUT_3, DATAOUT_2, DATAOUT_1, DATAOUT_0})
    );
endmodule
